// Подключение необходимых библиотек
#include <Arduino.h>    // Главная библиотека Arduino, обеспечивает базовые функции (pinMode, delay и т.д.)
#include <Wire.h>       // Библиотека для работы с шиной I2C, которая используется для связи с дисплеем.
#include <Adafruit_GFX.h> // Графическая библиотека от Adafruit. Она содержит базовые функции для рисования (точки, линии, текст) и является ядром.
#include <Adafruit_SSD1306.h> // Специализированная библиотека для дисплеев SSD1306. Она наследует Adafruit_GFX и добавляет специфичные для этого дисплея команды.
#include <Adafruit_NeoPixel.h> // Библиотека для управления адресными RGB-светодиодами (как ваш на пине 38).

// Конфигурация OLED-дисплея
#define SCREEN_WIDTH 128    // Ширина дисплея в пикселях
#define SCREEN_HEIGHT 32    // Высота дисплея в пикселях
#define OLED_RESET -1       // Определяем номер пина для сигнала сброса (reset) дисплея. 
                            // -1 означает, что аппаратный сброс не используется (часто пин RST дисплея подключен к сбросу платы или не используется).
#define I2C_SDA 8           // Пин GPIO8 для данных (SDA) I2C
#define I2C_SCL 9           // Пин GPIO9 для тактирования (SCL) I2C

#define OLED_ADDR 0x3C      // I2C-адрес дисплея для общения с ESP32 (0x3C или 0x3D)

// Создаем объект (экземпляр) дисплея
// Конструктору передаем параметры: ширина, высота, указатель на объект I2C (&Wire), и пин сброса.
Adafruit_SSD1306 display(SCREEN_WIDTH, SCREEN_HEIGHT, &Wire, OLED_RESET);

// Конфигурация RGB-светодиода
#define LED_PIN 38          // Пин GPIO38, к которому подключен светодиод
#define LED_COUNT 1         // Количество светодиодов в цепи (1 шт.)

// ВАЖНО: Мой Светодиод использует порядок цветов GRB (Green, Red, Blue), то есть NEO_GRB 
// Создаем объект (экземпляр) для управления лентой светодиодов с именем 'strip'.
// Конструктору передаем: количество светодиодов, пин управления, и тип светодиода (порядок цветов + частота).
// NEO_KHZ800 это частота 800 KHz для WS2812B RGB LED
Adafruit_NeoPixel strip(LED_COUNT, LED_PIN, NEO_GRB + NEO_KHZ800);

// Структура для удобного хранения связки "название цвета" и "его числовое значение"
struct Color {
  const char* name;   // Название цвета (для вывода на дисплей), например, "Red"
  uint32_t value;     // Числовое значение цвета для светодиода в формате, понятном библиотеке Adafruit_NeoPixel.
};

//  Создаем и заполняем массив структур 'colors'
// Этот массив будет хранить все цвета, которые мы хотим поочередно показывать.
// ЗНАЧЕНИЯ ПОДОБРАНЫ ИСХОДЯ ИЗ ПОРЯДКА GRB, КОТОРЫЙ ЖДЕТ СВЕТОДИОД:
// strip.Color(G, R, B) -> (Зеленый, Красный, Синий)
Color colors[] = {
  {"Green",  strip.Color(255, 0, 0)},   // G=255, R=0, B=0 -> Горит только зеленый канал -> ЗЕЛЕНЫЙ
  {"Red",    strip.Color(0, 255, 0)},   // G=0, R=255, B=0 -> Горит только красный канал -> КРАСНЫЙ
  {"Blue",   strip.Color(0, 0, 255)},   // G=0, R=0, B=255 -> Горит только синий канал -> СИНИЙ
  {"White",  strip.Color(255, 255, 255)}// G=255, R=255, B=255 -> Горят все каналы -> БЕЛЫЙ
};

// Вычисляем количество элементов в массиве colors
// sizeof(colors) - общий размер массива в байтах.
// sizeof(colors[0]) - размер одного элемента массива (одной структуры Color) в байтах.
int colorCount = sizeof(colors) / sizeof(colors[0]);

// Функция setup выполняется один раз при запуске или после сброса.
void setup() {
  // Инициализируем последовательный порт (UART) для отладки (115200 бод) для вывода сообщений в Монитор порта (Serial Monitor)
  Serial.begin(115200);

  // --- Инициализация дисплея ---
  Wire.begin(I2C_SDA, I2C_SCL); // Запускаем шину I2C на указанных пинах

  // Пытаемся найти и инициализировать дисплей по адресу OLED_ADDR
  // display.begin(...) возвращает false, если дисплей не ответил по I2C (проверьте провода и адрес!).
  // SSD1306_SWITCHCAPVCC - параметр, указывающий дисплею взять voltage 3.3V
  // OLED_ADDR равен 0x3C
  if (!display.begin(SSD1306_SWITCHCAPVCC, OLED_ADDR)) {
    Serial.println(F("SSD1306 initialization failed")); // Если не удалось - выводим ошибку
    for (;;); // И уходим в бесконечный цикл (программа "зависает")
  }

  // Настраиваем дисплей
  display.clearDisplay(); // Очищаем буфер дисплея, заполняем его нулями = черный цвет
  display.setTextSize(2); // Устанавливаем размер шрифта (1 - стандартный.
  // Можно использовать 2, 3 и т.д. для увеличения.)
  display.setTextColor(SSD1306_WHITE); // Устанавливаем цвет текста (белый на черном фоне)

  // --- Инициализация RGB-светодиода ---
  strip.begin();  // Инициализируем библиотеку NeoPixel для работы со светодиодом. Эта функция настраивает пин LED_PIN на выход.
  strip.show();   // отправляет текущее состояние буфера на светодиод. Так как буфер только что инициализирован (все светодиоды выключены), эта команда гасит светодиод.

}

// Функция loop выполняется бесконечно в цикле
void loop() {
  // Поочередно перебираем все цвета из массива 'colors' (от 0 до colorCount-1).
  for (int i = 0; i < colorCount; i++) {
    // 1. Устанавливаем текущий цвет для светодиода (в буфер)
    strip.setPixelColor(0, colors[i].value); // 0 - индекс первого (и единственного) светодиода
    
    // 2. Применяем изменения (зажигаем светодиод). Без этой команды изменения на светодиоде не отобразятся.
    strip.show(); 

    // 3. Обновляем информацию на дисплее
    display.clearDisplay();    // Очищаем буфер дисплея (в памяти МК), заливая его черным цветом.
    display.setCursor(0, 0);   // Ставим курсор в верхний левый угол (координаты X=0, Y=0)
    display.println("LED COLOR"); // Выводим заголовок
    display.setCursor(0, 18);  // Перемещаем курсор ниже (координаты X=0, Y=18 пикселей)
    display.println(colors[i].name); // Выводим название текущего цвета (colors[i].name) из массива
    display.display();         // Отправляем буфер на дисплей. Без этой команды на дисплее ничего не изменится.

    delay(1000); // Ждем 1000 миллисекунд (1 секунду)
  }
  // Цикл for завершается, и программа возвращается к его началу,
  // начиная перебирать цвета снова (зеленый -> красный -> синий -> белый -> зеленый -> ...)
}



